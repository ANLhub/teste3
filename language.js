    const languageButton = document.getElementById("languageButton");
    const languageMenu = document.getElementById("languageMenu");
    const languageFlag = document.getElementById("languageFlag");
    const languageName = document.getElementById("languageName");
    const siteSettingsButton = document.getElementById("siteSettingsButton");
    const siteSettingsMenu = document.getElementById("siteSettingsMenu");
    const siteLightMode = document.getElementById("siteLightMode");

    let currentLanguage = "pt-BR";
    let currentTheme = document.body.dataset.theme === "light" ? "light" : "dark";

    try {

        const savedLanguage = localStorage.getItem("video-studio-language");

        if (savedLanguage === "en" || savedLanguage === "pt-BR") {

            currentLanguage = savedLanguage;

        }

    } catch (error) {

        console.warn("Could not load the saved language preference.", error);

    }

    try {

        const savedTheme = localStorage.getItem("video-studio-theme");

        if (savedTheme === "light" || savedTheme === "dark") {

            currentTheme = savedTheme;

        }

    } catch (error) {

        console.warn("Could not load the saved theme preference.", error);

    }

    function applyTheme() {

        document.body.dataset.theme = currentTheme;
        siteLightMode.checked = currentTheme === "light";

    }

    applyTheme();

    function languageText(key, values = {}) {

        const template =
            translations[currentLanguage][key] ||
            translations["pt-BR"][key] ||
            key;

        return template.replace(
            /\{(\w+)\}/g,
            (match, name) => values[name] ?? match
        );

    }


    function applyLanguage() {

        document.documentElement.lang = currentLanguage;

        document.querySelectorAll("[data-i18n]")
            .forEach(
                element => {

                    element.textContent =
                        languageText(element.dataset.i18n);

                }
            );

        document.querySelectorAll("[data-i18n-title]")
            .forEach(
                element => {

                    element.title =
                        languageText(element.dataset.i18nTitle);

                }
            );

        document.querySelectorAll("[data-i18n-aria-label]")
            .forEach(
                element => {

                    element.setAttribute(
                        "aria-label",
                        languageText(element.dataset.i18nAriaLabel)
                    );

                }
            );

        languageFlag.textContent =
            currentLanguage === "pt-BR" ? "🇧🇷" : "🇺🇸";

        languageName.textContent =
            currentLanguage === "pt-BR" ? "Português" : "English";

        document.querySelectorAll("[data-language]")
            .forEach(
                option => {

                    option.setAttribute(
                        "aria-pressed",
                        String(option.dataset.language === currentLanguage)
                    );

                }
            );

        document.dispatchEvent(
            new CustomEvent("app-language-change", {
                detail: { language: currentLanguage }
            })
        );

    }


    function setLanguage(language) {

        if (!translations[language]) {

            return;

        }

        currentLanguage = language;

        try {

            localStorage.setItem("video-studio-language", language);

        } catch (error) {

            console.warn("Could not save the language preference.", error);

        }

        applyLanguage();

        languageMenu.hidden = true;
        languageButton.setAttribute("aria-expanded", "false");

    }


    languageButton.addEventListener(
        "click",
        () => {

            siteSettingsMenu.hidden = true;
            siteSettingsButton.setAttribute("aria-expanded", "false");
            languageMenu.hidden = !languageMenu.hidden;
            languageButton.setAttribute(
                "aria-expanded",
                String(!languageMenu.hidden)
            );

        }
    );

    languageMenu.addEventListener(
        "click",
        event => {

            const option = event.target.closest("[data-language]");

            if (option) {

                setLanguage(option.dataset.language);

            }

        }
    );

    siteSettingsButton.addEventListener(
        "click",
        () => {

            languageMenu.hidden = true;
            languageButton.setAttribute("aria-expanded", "false");
            siteSettingsMenu.hidden = !siteSettingsMenu.hidden;
            siteSettingsButton.setAttribute(
                "aria-expanded",
                String(!siteSettingsMenu.hidden)
            );

        }
    );

    siteLightMode.addEventListener(
        "change",
        () => {

            currentTheme = siteLightMode.checked ? "light" : "dark";

            try {

                localStorage.setItem("video-studio-theme", currentTheme);

            } catch (error) {

                console.warn("Could not save the theme preference.", error);

            }

            applyTheme();

        }
    );

    document.addEventListener(
        "click",
        event => {

            if (!event.target.closest(".language-selector")) {

                languageMenu.hidden = true;
                languageButton.setAttribute("aria-expanded", "false");

            }

            if (!event.target.closest(".site-settings-selector")) {

                siteSettingsMenu.hidden = true;
                siteSettingsButton.setAttribute("aria-expanded", "false");

            }

        }
    );

    document.addEventListener(
        "keydown",
        event => {

            if (event.key === "Escape") {

                languageMenu.hidden = true;
                languageButton.setAttribute("aria-expanded", "false");

                if (!siteSettingsMenu.hidden) {

                    siteSettingsMenu.hidden = true;
                    siteSettingsButton.setAttribute("aria-expanded", "false");
                    siteSettingsButton.focus();

                } else {

                    languageButton.focus();

                }

            }

        }
    );

    window.languageText = languageText;
    window.getSiteLanguage = () => currentLanguage;

    applyLanguage();

